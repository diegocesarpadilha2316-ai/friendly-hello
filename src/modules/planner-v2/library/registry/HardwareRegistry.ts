const byId = new Map(HARDWARE.map((item) => [item.id, item]));

export const HardwareRegistry = {
  list: (): HardwareDefinition[] => [...HARDWARE],
  get: (id: string): HardwareDefinition | undefined => byId.get(id),
  getManufacturingVariant: (hardwareId: string, variantId?: string) => {
    const hardware = byId.get(hardwareId);
    if (!hardware || !variantId) return undefined;
    return hardware.manufacturingVariants?.find((variant) => variant.id === variantId);
  },
  has: (id: string): boolean => byId.has(id),
  listByCategory: (category: HardwareDefinition["category"]) =>
    HARDWARE.filter((item) => item.category === category),
};
